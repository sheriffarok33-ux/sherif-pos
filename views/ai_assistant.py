import streamlit as st


def show_page():
    st.markdown("## 🤖 المساعد الذكي للأعمال")
    st.info("🟡 الحالة: قيد التجهيز — سيتم تفعيل الاتصال بالذكاء الاصطناعي بعد الانتهاء من تعديلات النظام الحالية.")
    st.markdown(
        """
        المساعد الذكي سيكون جزءًا من نظام الإدارة، ويهدف إلى مساعدة الإدارة في فهم بيانات العمل
        بسرعة باللغة العربية، مع الالتزام بصلاحيات المستخدم والفروع.
        """
    )

    st.markdown("### أمثلة لما سيتمكن المساعد من تنفيذه")
    examples = [
        "📊 حلل مبيعات اليوم وقارن أداء الفروع.",
        "💰 ما الأصناف الأعلى ربحية خلال الفترة؟",
        "📦 ما الأصناف منخفضة المخزون أو القريبة من انتهاء الصلاحية؟",
        "🧾 لخص المشتريات والمصروفات والإيرادات.",
        "👥 اعرض ملخص الدائنين والمدينين وجهات التعامل.",
        "🏦 أعطني ملخصًا عن الخزائن والحركة المالية.",
    ]
    for item in examples:
        st.markdown(f"- {item}")

    st.markdown("---")
    st.text_input(
        "اكتب سؤالك للمساعد",
        placeholder="مثال: قارن مبيعات الفروع اليوم",
        disabled=True,
        key="ai_preview_question",
    )
    st.button("إرسال للمساعد", disabled=True, use_container_width=True, key="ai_preview_send")
    st.caption("هذه شاشة عرض للميزة القادمة فقط. لا يوجد اتصال بخدمة AI ولا يتم إرسال أي بيانات حاليًا.")
